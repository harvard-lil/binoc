//! Regenerate `docs/reference/cli.md` from the clap `Command` tree.
//!
//! Usage: `emit-cli-markdown [PATH]`
//!
//! PATH defaults to `docs/reference/cli.md` resolved relative to the workspace
//! root. The file must already exist and contain the begin/end marker pair
//! declared below; only the content between the markers is rewritten, so the
//! authored frontmatter and intro above the generated block survive.
//!
//! See ADR documentation_platform_and_info_design.md §4 for why the CLI
//! reference is generated.

use std::path::{Path, PathBuf};

const BEGIN_MARKER: &str = "<!-- BEGIN AUTOGENERATED CLI REFERENCE -->";
const END_MARKER: &str = "<!-- END AUTOGENERATED CLI REFERENCE -->";

fn default_output_path() -> PathBuf {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    // CARGO_MANIFEST_DIR is binoc-cli/; the workspace root is its parent.
    manifest_dir
        .parent()
        .unwrap_or(manifest_dir)
        .join("docs/reference/cli.md")
}

fn strip_generator_preamble(generated: &str) -> &str {
    // clap-markdown always emits a `# {title}` header and a one-line
    // description sentence before the command overview. We already have a
    // page heading in the authored framing, so skip straight to the
    // "**Command Overview:**" block if present, otherwise to the first
    // `## ` section.
    if let Some(idx) = generated.find("**Command Overview:**") {
        return &generated[idx..];
    }
    if let Some(idx) = generated.find("\n## ") {
        return generated[idx..].trim_start_matches('\n');
    }
    generated
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut args = std::env::args().skip(1);
    let output_path = match args.next() {
        Some(p) => PathBuf::from(p),
        None => default_output_path(),
    };

    let options = clap_markdown::MarkdownOptions::new()
        .title("Command-line reference".to_string())
        .show_footer(false)
        .show_table_of_contents(true)
        .show_aliases(false);
    let generated = clap_markdown::help_markdown_command_custom(&binoc_cli::command(), &options);
    let generated = strip_generator_preamble(&generated).trim_end();

    let existing = std::fs::read_to_string(&output_path).map_err(|e| {
        format!(
            "failed to read {}: {e}. Create the file with the BEGIN/END \
             marker pair before running this generator.",
            output_path.display()
        )
    })?;

    let begin_idx = existing.find(BEGIN_MARKER).ok_or_else(|| {
        format!(
            "{} is missing the `{BEGIN_MARKER}` marker",
            output_path.display()
        )
    })?;
    let end_idx = existing.find(END_MARKER).ok_or_else(|| {
        format!(
            "{} is missing the `{END_MARKER}` marker",
            output_path.display()
        )
    })?;
    if end_idx < begin_idx {
        return Err(format!(
            "{}: END marker appears before BEGIN marker",
            output_path.display()
        )
        .into());
    }

    let before = &existing[..begin_idx + BEGIN_MARKER.len()];
    let after = &existing[end_idx..];
    let new_contents = format!("{before}\n\n{generated}\n\n{after}");

    if new_contents == existing {
        println!("{} is up to date.", output_path.display());
    } else {
        std::fs::write(&output_path, &new_contents)?;
        println!("Wrote {}.", output_path.display());
    }

    Ok(())
}
